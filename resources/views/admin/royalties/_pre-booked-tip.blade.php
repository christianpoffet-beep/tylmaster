{{-- What "Bereits pauschal gebucht" does - on the statement form and the draft --}}
<x-admin.info-tip>
    Ändert die Verteilung nicht, nur die Buchung. Die Anteile der Künstler:innen werden immer genau berechnet und ihren Saldi gutgeschrieben.
    Liegt für diesen Zeitraum aber schon eine Pauschale auf den Kreditoren (z.B. 80 % Ende Jahr), wird nur die Differenz gebucht – sonst stünde sie doppelt dort.
    Beispiel: Anteile CHF 470, pauschal gebucht 815.08 → Rückbuchung CHF 345.08, danach liegen genau CHF 470 auf den Kreditoren.
    Bei der ersten Abrechnung 2023–2025: 815.08.
</x-admin.info-tip>
